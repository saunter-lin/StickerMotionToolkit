def translate(language: str, key: str, **values: object) -> str:
    """Look up and format a string, falling back to the default catalog."""
    catalog = TRANSLATIONS.get(language, TRANSLATIONS[DEFAULT_LANGUAGE])
    template = catalog.get(key, TRANSLATIONS[DEFAULT_LANGUAGE].get(key, key))
    return template.format(**values)


def localized_error(language: str, error: Exception) -> str:
    """Convert common processing failures into safe localized messages."""
    message = str(error)
    if isinstance(error, FileNotFoundError):
        return translate(language, "error_file_not_found")
    if isinstance(error, PermissionError):
        return translate(language, "error_permission")
    if "frame_count" in message or "animations require" in message:
        return translate(language, "error_invalid_frames")
    if "not evenly divisible" in message:
        return translate(language, "error_invalid_sheet")
    return message
